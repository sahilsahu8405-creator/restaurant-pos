import React, { useState } from 'react';
import { X, Tv, CheckCircle2, AlertCircle, Loader2, ArrowRight } from 'lucide-react';
import { useAuth } from '../../context/AuthContext';

interface KdsPairingModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const KdsPairingModal: React.FC<KdsPairingModalProps> = ({ isOpen, onClose }) => {
  const { pairKdsTerminal, isLoading, error, clearError } = useAuth();
  const [pairingCode, setPairingCode] = useState('');
  const [success, setSuccess] = useState(false);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!pairingCode.trim()) return;
    clearError();
    try {
      await pairKdsTerminal(pairingCode.trim());
      setSuccess(true);
      setTimeout(() => {
        onClose();
      }, 1500);
    } catch {
      // Error handled in AuthContext
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-xs animate-fade-in select-none">
      <div className="bg-slate-900 border border-slate-800 rounded-3xl max-w-md w-full p-6 text-slate-100 shadow-2xl relative">
        <button
          onClick={onClose}
          className="absolute top-5 right-5 p-1.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
        >
          <X className="w-5 h-5" />
        </button>

        <div className="space-y-1 mb-6">
          <div className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase bg-purple-500/20 text-purple-400 border border-purple-500/30">
            <Tv className="w-3 h-3" />
            <span>Kitchen Display System</span>
          </div>
          <h2 className="text-xl font-black text-white">Pair Kitchen Display Terminal</h2>
          <p className="text-xs text-slate-400">
            Enter the 6-digit terminal pairing code generated by your manager or owner in Restaurant Settings &gt; Kitchen Stations.
          </p>
        </div>

        {error && (
          <div className="mb-4 p-3 rounded-xl bg-rose-950/60 border border-rose-800 text-rose-200 text-xs flex items-start gap-2">
            <AlertCircle className="w-4 h-4 text-rose-400 shrink-0 mt-0.5" />
            <div>{error}</div>
          </div>
        )}

        {success && (
          <div className="mb-4 p-3 rounded-xl bg-emerald-950/60 border border-emerald-800 text-emerald-200 text-xs flex items-center gap-2">
            <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
            <div>Terminal successfully paired! Opening scoped Kitchen Display...</div>
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <label className="block text-xs font-bold text-slate-300 mb-1.5 text-center">
              6-Digit Pairing Code
            </label>
            <input
              type="text"
              maxLength={6}
              value={pairingCode}
              onChange={(e) => setPairingCode(e.target.value.replace(/\D/g, ''))}
              placeholder="482910"
              required
              autoFocus
              className="w-full bg-slate-800 border border-slate-700 rounded-2xl py-4 text-center font-mono text-3xl font-black tracking-widest text-white placeholder-slate-600 focus:outline-none focus:border-purple-500"
            />
          </div>

          <div className="p-3 rounded-xl bg-slate-800/40 border border-slate-700/60 text-[11px] text-slate-400">
            Pairing binds this physical tablet or screen strictly to its assigned kitchen station and outlet. No billing, financial reports, or owner settings can be accessed from this terminal.
          </div>

          <div className="flex gap-2 pt-2">
            <button
              type="button"
              onClick={onClose}
              className="flex-1 py-2.5 rounded-xl border border-slate-700 hover:bg-slate-800 text-slate-300 text-xs font-bold transition-all"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isLoading || pairingCode.length < 6}
              className="flex-1 py-2.5 rounded-xl bg-purple-600 hover:bg-purple-500 text-white text-xs font-bold shadow-lg shadow-purple-600/30 flex items-center justify-center gap-1.5 transition-all disabled:opacity-50 cursor-pointer"
            >
              {isLoading ? (
                <>
                  <Loader2 className="w-3.5 h-3.5 animate-spin" />
                  <span>Pairing...</span>
                </>
              ) : (
                <>
                  <span>Pair Device</span>
                  <ArrowRight className="w-3.5 h-3.5" />
                </>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
